'use strict';
const assert=require('node:assert/strict');
const r=require('./reminders.js');
const event={date:'2027-01-01',allDay:false,start:'00:05',reminder:'10'};
assert.equal(r.resolve(event),'2026-12-31T23:55');
assert.equal(r.resolve({...event,date:'2028-03-01',start:'00:15',reminder:'30'}),'2028-02-29T23:45');
assert.equal(r.resolve({...event,date:'2027-03-01',start:'00:15',reminder:'30'}),'2027-02-28T23:45');
assert.equal(r.resolve({...event,allDay:true,reminder:'previous9'}),'2026-12-31T09:00');
const offset={mode:'offset',amount:25,unit:'minutes'};
assert.equal(r.resolve({...event,reminder:'custom',customReminder:offset}),'2026-12-31T23:40');
assert.equal(r.resolve({...event,reminder:'custom',customReminder:{...offset,amount:3,unit:'hours'}}),'2026-12-31T21:05');
assert.equal(r.resolve({...event,allDay:true,reminder:'custom',customReminder:{...offset,amount:2,unit:'days'}}),'2026-12-30T09:00');
assert.equal(r.resolve({...event,allDay:true,reminder:'custom',customReminder:{...offset,amount:0}}),'2027-01-01T09:00');
const exact={mode:'datetime',at:'2028-02-29T07:45'};
assert.equal(r.resolve({...event,reminder:'custom',customReminder:exact}),exact.at);
assert.equal(r.resolve({...event,date:'2030-10-02',start:'11:00',reminder:'custom',customReminder:exact}),exact.at,'Specific times survive moving an event');
assert.equal(new Date(exact.at+':00+08:00').toISOString(),'2028-02-28T23:45:00.000Z');
assert.equal(r.validDateTime('2027-02-29T09:00'),false);
assert.equal(r.validDateTime('2028-02-29T24:00'),false);
assert.ok(r.checkCustom(event,{...offset,amount:-1}).error);
assert.ok(r.checkCustom(event,{...offset,amount:1.5}).error);
assert.ok(r.checkCustom(event,{...offset,amount:366,unit:'days'}).error);
assert.ok(r.checkCustom({...event,date:'1900-01-01'},offset).error);
assert.equal(r.normalize({...exact,at:'<invalid>'}),null);
assert.equal(r.resolve({...event,reminder:'none'}),null);
assert.equal(r.label('2028-02-29T07:45'),'2028年2月29日 07:45');
console.log('Reminder checks passed: custom intervals, specific times, year/month boundaries, leap years and invalid input.');
